  // Loot item reveal based on rarity
  public playLootReveal(rarity: string) {
    if (this.muted) return;
    if (rarity === 'mythic' || rarity === 'legendary') {
      this.playFreeSpinsTrigger();
    } else if (rarity === 'epic') {
      this.playWinChime(4);
    } else if (rarity === 'rare') {
      this.playWinChime(1);
    } else {
      this.playCoin();
    }
  }
